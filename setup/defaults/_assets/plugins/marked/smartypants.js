/* @plugin-name: SmartPants (Typography) */
/* @plugin-version: 1.2.0 */
/* @marked: >=14 <19 */
//
// 文章中の記号をタイポグラフィ的に美しい文字に変換する。
//
//   "hello"  → "hello"  （カーリーダブルクォート）
//   'hello'  → 'hello'  （カーリーシングルクォート）
//   it's     → it's     （アポストロフィ）
//   ---      → —        （エムダッシュ）
//   --       → –        （エンダッシュ）
//   ...      → …        （省略記号）
//
(function() {
  function convert(src) {
    return src
      // エムダッシュ（--- の前に処理）
      .replace(/---/g, '—')
      // エンダッシュ
      .replace(/--/g, '–')
      // 省略記号
      .replace(/\.\.\./g, '…')
      // 開きダブルクォート：空白・行頭・開き括弧の後の "
      .replace(/(^|[\s\(\[\{<])"(?=\S)/gm, '$1“')
      // 閉じダブルクォート：残り全て
      .replace(/"/g, '”')
      // 開きシングルクォート：空白・行頭・開き括弧の後の '
      .replace(/(^|[\s\(\[\{<])'(?=\S)/gm, '$1‘')
      // 閉じシングルクォート・アポストロフィ：残り全て
      .replace(/'/g, '’');
  }

  return {
    hooks: {
      preprocess: function(src) {
        // 変換してはいけない箇所を退避してから変換する。
        //
        //   <!--...-->        HTMLコメント
        //   <script>/<style>  中身は JS / CSS
        //   ```...``` / `...` コードブロック・インラインコード
        //   <tag ...>         生HTMLのタグ（属性値を壊さないため）
        //   ---, ***, ___     水平線（行全体が記号のみの行）
        //   |:---|---:|       テーブルの区切り行
        //
        // タグを保護しないと属性値のクォートがカーリークォートに化け、
        // 例えば drawLayer が出力する SVG が viewBox=”0 0 1.5 1” となって
        // 描画に失敗する（"Expected number" になる）。CSS カスタムプロパティの
        // var(--x) がエンダッシュ化する問題も同じ理由で防げる。
        // タグの中身（テキストノード）は保護対象外なので通常どおり変換される。
        //
        // テーブルの区切り行（|:---|---:| 等）も保護する。ここを変換すると
        // ---- がエムダッシュ・エンダッシュに化けて marked がテーブルと認識できず、
        // 表全体がただの段落として出力される。セル本文は保護対象外なので
        // 通常どおり変換される。
        var blocks = [];
        var result = src.replace(/<!--[\s\S]*?-->|<(script|style)\b[\s\S]*?<\/\1>|```[\s\S]*?```|`[^`\n]+`|<\/?[a-zA-Z][^<>]*>|^[ \t]*(?:-[ \t]*){3,}$|^[ \t]*(?:\*[ \t]*){3,}$|^[ \t]*(?:_[ \t]*){3,}$|^(?=[^\n]*\|)(?=[^\n]*-)[ \t]*[-:|][-:| \t]*\r?$/gm, function(m) {
          blocks.push(m);
          return '\x00CODE' + (blocks.length - 1) + '\x00';
        });
        result = convert(result);
        // 退避していたコードを復元
        return result.replace(/\x00CODE(\d+)\x00/g, function(_, i) {
          return blocks[parseInt(i, 10)];
        });
      }
    }
  };
})();
